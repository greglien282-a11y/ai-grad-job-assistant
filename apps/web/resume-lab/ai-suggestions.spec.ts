import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const raw = '项目经历\r\n👩‍💻 é 我编写了Python课程脚本。\r\n\r\n团队负责，我计划学习部署。'
test('offline candidate review is real UI, exact original can enter a user draft and unsafe rewrite stays quarantined', async ({ page }, info) => {
  const effects: string[] = []
  page.on('request', r => { if (r.method() !== 'GET' || !r.url().startsWith('http://127.0.0.1:15191/') || r.url().includes('/api/')) effects.push(r.url()) })
  await page.goto('/resume-lab'); await page.getByLabel('简历原文', { exact: true }).fill(raw)
  await page.getByRole('button', { name: '导入并核对原文' }).click(); await page.getByRole('button', { name: '新增Python后端实习生草稿' }).click()
  const panel = page.getByRole('region', { name: '离线AI建议审核实验室' })
  await expect(panel).toContainText('Mock不是模型'); await page.getByRole('button', { name: '生成离线Mock候选' }).click()
  const candidate = panel.getByRole('article', { name: '建议候选 mock:1' })
  await expect(candidate).toContainText('👩‍💻 é 我编写了Python课程脚本。'); await expect(candidate).toContainText('JD 条件Python后端实习生'); await expect(panel).toContainText('必备：Python基础与测试意识。')
  await expect(page.getByLabel('选用条目 1', { exact: true })).not.toBeChecked()
  await panel.screenshot({ path: info.outputPath('resume_m25_mock_review.png') })
  await page.getByRole('button', { name: '接受原句顺序 · mock:1', exact: true }).click()
  const paper = page.getByRole('article', { name: '用户自述简历草稿' }); await expect(paper).toContainText('👩‍💻 é 我编写了Python课程脚本。')
  await expect(paper).toContainText('未经平台核实')
  await page.getByRole('button', { name: '查看公开合成风险反例' }).click()
  const risk = panel.getByRole('article', { name: '建议候选 risk:unsupported' })
  await expect(risk).toContainText('需要人工澄清'); await expect(risk.getByRole('button', { name: '接受原句顺序 · risk:unsupported' })).toBeDisabled()
  await expect(risk).toContainText('提升30%'); await expect(paper).not.toContainText('30%')
  await risk.getByRole('textbox', { name: '待核对候选文字 · risk:unsupported', exact: true }).fill('<img src="https://example.invalid/p" onerror="alert(1)"> 用户暂存，需要证据')
  await page.getByRole('button', { name: '保留编辑到待核对区 · risk:unsupported' }).click(); await expect(panel).toContainText('用户编辑待核对，未应用')
  await expect(paper).not.toContainText('用户暂存'); await expect(page.locator('.resume-lab img,.resume-lab script')).toHaveCount(0)
  await panel.screenshot({ path: info.outputPath('resume_m25_quarantined_edit.png') })
  await page.getByRole('button', { name: '拒绝候选 · risk:unsupported' }).click(); await page.getByRole('button', { name: '查看公开合成风险反例' }).click()
  await expect(panel).toContainText('已拒绝（重新生成同一候选不解除）')
  const event = page.waitForEvent('download'); await page.getByRole('button', { name: '下载本地草稿 JSON' }).click()
  const file = await event, bytes = await readFile((await file.path())!), saved = JSON.parse(bytes.toString('utf8'))
  expect(saved.contract).toBe('local-job-resume-draft-v3'); expect(saved).not.toHaveProperty('suggestions'); expect(bytes.toString()).not.toContain('用户暂存')
  await page.reload(); await expect(page.getByLabel('完整简历原文')).toHaveCount(0)
  await page.getByLabel('恢复本地草稿 JSON').setInputFiles({ name: 'user-draft.json', mimeType: 'application/json', buffer: bytes })
  await expect(paper).toContainText('Python课程脚本'); await expect(panel.getByRole('article')).toHaveCount(0)
  expect(effects).toEqual([]); expect(await page.evaluate(async () => [localStorage.length, sessionStorage.length, (await indexedDB.databases()).length, (await caches.keys()).length])).toEqual([0, 0, 0, 0])
})

test('candidate errors and changed context clear old suggestions; no external provider or old candidate fallback', async ({ page }) => {
  await page.goto('/resume-lab'); await page.getByLabel('简历原文', { exact: true }).fill(raw); await page.getByRole('button', { name: '导入并核对原文' }).click(); await page.getByRole('button', { name: '新增Python后端实习生草稿' }).click()
  await page.getByRole('button', { name: '生成关键词对照候选' }).click()
  const panel = page.getByRole('region', { name: '离线AI建议审核实验室' }); await expect(panel).toContainText('deterministic_rule')
  await page.getByLabel('排版密度').selectOption('compact'); await expect(panel).toContainText('deterministic_rule')
  await page.getByRole('textbox', { name: '条件描述 jd-0-11', exact: true }).fill('用户调整为其他要求。')
  await expect(panel).toContainText('旧候选已失效'); await expect(panel.getByRole('article')).toHaveCount(0)
  await page.getByRole('button', { name: '生成关键词对照候选' }).click()
  await page.getByRole('textbox', { name: '岗位草稿 1', exact: true }).fill('用户重新核对的内容。')
  await expect(panel).toContainText('旧候选已失效'); await expect(panel.getByRole('article')).toHaveCount(0)
  await panel.getByText('载入本地标准候选 JSON（不上传）', { exact: true }).click()
  await page.getByLabel('候选 JSON', { exact: true }).fill('{"contract":"future-v2"}'); await page.getByRole('button', { name: '严格载入候选' }).click()
  await expect(panel.getByRole('alert')).toContainText('版本、字段、来源、Unicode引用或岗位快照不一致'); await expect(panel.getByRole('article')).toHaveCount(0)
  await page.getByRole('button', { name: '新增软件测试实习生草稿' }).click(); await expect(panel.getByRole('article')).toHaveCount(0)
  await expect(panel).toContainText('没有真实Provider、密钥读取或网络调用路径')
})
