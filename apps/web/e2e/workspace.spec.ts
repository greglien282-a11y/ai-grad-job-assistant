  expect(materialData.facts[0].status).toBe(probe().facts[0].status)
  expect(materialData.evidence.map((item: { material_reference: string; basis: string; reviewer: string }) => ({ material_reference: item.material_reference, basis: item.basis, reviewer: item.reviewer }))).toEqual(probe().materials)
  await page.screenshot({ path: info.outputPath('desktop_workspace.png'), fullPage: true })
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出资料', exact: true }).click()
  const file = await (await downloaded).path()
  if (!file) throw new Error('Export file unavailable')
  const exportedText = readFileSync(file, 'utf8')
  const c = await credentials(page)
  // Never compare/assert credential strings: failures must not print them.
  expect(exportedText.includes(c.token)).toBe(false)
  expect(exportedText.includes('access_token_hash')).toBe(false)
  const exported = JSON.parse(exportedText)
  expect(exported.data.facts[0].version).toBe(probe().facts[0].version)
  expect(exported.data.history.length).toBe(probe().history)
  await page.getByRole('button', { name: '结束会话', exact: true }).click()
  await page.getByRole('button', { name: '取消结束', exact: true }).click()
  expect(probe().sessions[0].status).toBe('active')
  await page.getByRole('button', { name: '结束会话', exact: true }).click()
