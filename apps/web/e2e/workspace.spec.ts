test('keyboard edit works before rejection; rejected statement cannot be revived', async ({ page }) => {
  await create(page); await add(page)
  await page.getByRole('button', { name: '编辑陈述', exact: true }).click()
  await page.getByLabel('编辑事实 1').fill('Synthetic corrected pending statement')
  await page.getByRole('button', { name: '保存编辑', exact: true }).click()
  await expect(page.getByText('待确认', { exact: true })).toBeVisible()
  await expect(page.getByLabel('编辑事实 1')).toBeHidden()
  await expect(page.getByRole('button', { name: '确认事实', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '确认事实', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText('用户确认', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '拒绝事实', exact: true }).click()
  await expect(page.getByText('已拒绝', { exact: true })).toBeVisible()
  const before = probe()
  expect(before.facts[0].status).toBe('rejected')
  await page.getByRole('button', { name: '编辑陈述', exact: true }).click()
  await page.getByLabel('编辑事实 1').fill('Synthetic forbidden resurrection')
  const denied = page.waitForResponse(response => response.request().method() === 'PATCH' && response.url().includes('/facts/'))
  await page.getByRole('button', { name: '保存编辑', exact: true }).click()
  expect((await denied).status()).toBe(409)
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByText('已拒绝', { exact: true })).toBeVisible()
  await expect(page.getByLabel('编辑事实 1')).toHaveValue('Synthetic forbidden resurrection')
  expect(probe().facts).toEqual(before.facts)
  expect(probe().facts[0].version).toBe(4)
  expect(probe().history).toBe(4)
})

