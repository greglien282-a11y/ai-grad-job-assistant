test('acceptance blocker: lost create response must not leave an unrecoverable session', async ({ page }) => {
  await page.goto('/manual')
  await page.route('**/api/v1/experience/sessions', async route => {
    const response = await forward(route)
    expect(response.status()).toBe(201)
    await route.abort('connectionreset')
  }, { times: 1 })
  await page.getByLabel('原始经历').fill('Synthetic lost create response')
  await page.getByRole('button', { name: '创建经历会话 →', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  expect(probe().sessions.length).toBe(1)
  const recoverable = await page.evaluate(() => sessionStorage.getItem('pathwise.development.session') !== null)
  expect(recoverable, 'A committed session must retain a recoverable credential after response loss').toBe(true)
})

