  await expect(page.getByText('已结束 · 只读', { exact: true })).toBeVisible()
  expect(probe().sessions[0].status).toBe('ended')
  await expect(page.getByRole('button', { name: '编辑陈述', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '删除会话', exact: true }).click()
  await page.getByRole('button', { name: '取消删除', exact: true }).click()
