test('committed edit whose response is lost is reconciled by a fresh read', async ({ page }) => {
  await create(page); await add(page)
  await page.route('**/api/v1/experience/facts/*', async route => {
    if (route.request().method() === 'PATCH') { const response = await forward(route); expect(response.status()).toBe(200); await route.abort('connectionreset') }
    else await route.fallback()
  }, { times: 1 })
  await page.getByRole('button', { name: '编辑陈述', exact: true }).click()
  await page.getByLabel('编辑事实 1').fill('Synthetic committed but response lost')
  await page.getByRole('button', { name: '保存编辑', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  expect(probe().facts[0].version).toBe(2)
  await page.getByRole('button', { name: '重新读取', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Synthetic committed but response lost', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '保存编辑', exact: true })).toBeDisabled()
  expect(probe().history).toBe(2)
})

